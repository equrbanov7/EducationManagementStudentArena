def _group(fixes):
    grouped = defaultdict(list)
    for (domain, lang, ctx, msgid), new in fixes.items():
        grouped[(domain, lang)].append((ctx, msgid, new))
    return grouped


def _short(text, limit=90):
    text = text.replace("\n", "⏎")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--locale-dir",
        default=os.path.join(BASE, "locale"),
        help="locale/ qovluğu (default: repo locale/)",
    )
    parser.add_argument("--dry-run", action="store_true", help="dəyişiklikləri göstər, yazma")
    args = parser.parse_args(argv)

    total_changed = total_missing = 0
    for (domain, lang), items in sorted(_group(FIXES).items()):
        path = os.path.join(args.locale_dir, lang, "LC_MESSAGES", f"{domain}.po")
        if not os.path.exists(path):
            print(f"{domain}/{lang}: fayl yoxdur, keçildi ({path})")
            continue
        po = polib.pofile(path)
        index = defaultdict(list)
        for entry in po:
            if not entry.obsolete and not entry.msgid_plural:
                index[(entry.msgctxt, entry.msgid)].append(entry)
        changed = missing = 0
        for ctx, msgid, new in items:
            entries = index.get((ctx, msgid))
            if not entries:
                missing += 1
                print(f"{domain}/{lang}: [{ctx}] {_short(msgid)!r}: giriş tapılmadı, keçildi")
                continue
            for entry in entries:
                if entry.msgstr == new:
                    continue
                print(f"{domain}/{lang}: [{ctx}] {_short(msgid)}: «{_short(entry.msgstr)}» → «{_short(new)}»")
                entry.msgstr = new
                if "fuzzy" in entry.flags:
                    entry.flags.remove("fuzzy")
                changed += 1
        if changed and not args.dry_run:
            po.save(path)
            subprocess.check_call(["msgfmt", "--check-format", "-o", path[:-3] + ".mo", path])
        print(f"{domain}/{lang}: {changed} dəyişiklik, {missing} tapılmadı")
        total_changed += changed
        total_missing += missing
    print(f"Cəmi: {total_changed} dəyişiklik, {total_missing} tapılmadı" + (" (dry-run)" if args.dry_run else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
